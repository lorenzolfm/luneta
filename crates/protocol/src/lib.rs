impl v1::Agent {
    #[must_use]
    pub fn runs_in(&self) -> v1::Harness {
        match self.harness {
            None => v1::Harness::ClaudeCode,
            Some(said) => v1::Harness::try_from(said).unwrap_or(v1::Harness::Unspecified),
        }
    }

    #[must_use]
    pub fn at_a_prompt(&self) -> bool {
        let word = self.runs_in().prompt_word();
        word.is_some_and(|word| self.entrypoint.as_deref() == Some(word))
    }

    #[must_use]
    pub fn is_finished_turn(&self) -> bool {
        agent_status::AgentStatus::of_api(self).is_finished_turn()
    }

    #[must_use]
    pub fn live_topic(&self) -> Option<&str> {
        let topic = self.topic.as_deref()?.trim();
        (!topic.is_empty()).then_some(topic)
    }

    #[must_use]
    pub fn parsed_telemetry(&self) -> Option<telemetry::AgentTelemetry> {
        self.telemetry
            .as_ref()
            .and_then(telemetry::AgentTelemetry::of_api)
    }
}

